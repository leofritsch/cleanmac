import Foundation

enum ProjectScanner {
    struct Rule {
        let folder: String
        let title: String
        let note: String
        /// Any of these must sit next to the folder for it to count (avoids matching a random "target").
        var markers: [String] = []
        /// File that must exist inside the folder.
        var inside: String? = nil
    }

    static let rules: [Rule] = [
        Rule(folder: "node_modules", title: "node_modules", note: "JavaScript dependencies. npm, pnpm, yarn or bun install puts them back.", markers: ["package.json"]),
        Rule(folder: ".next", title: "Next.js build cache", note: "Build output and cache. next build or next dev recreates it."),
        Rule(folder: ".nuxt", title: "Nuxt build", note: "Generated by nuxt dev and nuxt build."),
        Rule(folder: ".svelte-kit", title: "SvelteKit build", note: "Generated by the SvelteKit dev server and builds."),
        Rule(folder: ".turbo", title: "Turborepo cache", note: "Task output cache for turbo."),
        Rule(folder: ".parcel-cache", title: "Parcel cache", note: "Bundler cache."),
        Rule(folder: ".angular", title: "Angular cache", note: "Angular CLI build cache."),
        Rule(folder: ".expo", title: "Expo project cache", note: "Generated by Expo while developing.", markers: ["app.json", "app.config.js", "app.config.ts"]),
        Rule(folder: "target", title: "Rust & Maven builds", note: "Compiled output. cargo build or mvn package rebuilds it.", markers: ["Cargo.toml", "pom.xml"]),
        Rule(folder: ".build", title: "Swift package builds", note: "SwiftPM build folder. swift build recreates it.", markers: ["Package.swift"]),
        Rule(folder: "Pods", title: "CocoaPods", note: "Installed pods. pod install puts them back.", markers: ["Podfile"]),
        Rule(folder: "DerivedData", title: "Project DerivedData", note: "Xcode build folder kept inside the project."),
        Rule(folder: ".gradle", title: "Gradle project cache", note: "Per-project Gradle state.", markers: ["build.gradle", "build.gradle.kts", "settings.gradle", "settings.gradle.kts"]),
        Rule(folder: ".dart_tool", title: "Dart tool cache", note: "Generated by flutter pub get.", markers: ["pubspec.yaml"]),
        Rule(folder: ".venv", title: "Python virtual environments", note: "Recreate with python -m venv and your requirements.", inside: "pyvenv.cfg"),
        Rule(folder: "venv", title: "Python virtual environments", note: "Recreate with python -m venv and your requirements.", inside: "pyvenv.cfg"),
        Rule(folder: ".terraform", title: "Terraform providers", note: "terraform init downloads them again.", markers: ["main.tf", "versions.tf", "providers.tf"]),
    ]

    private static let rulesByFolder = Dictionary(grouping: rules, by: \.folder)
    private static let skipNames: Set<String> = [".git", ".hg", ".svn", ".Trash", "Library", ".cache", ".idea", ".vscode"]

    static let defaultsKey = "projectRoots"

    static func storedRoots() -> [URL] {
        if let saved = UserDefaults.standard.array(forKey: defaultsKey) as? [String] {
            return saved.map { URL(fileURLWithPath: $0) }
        }
        let guesses = ["Code", "Developer", "Projects", "dev", "Dev", "src", "Sites", "repos", "workspace", "GitHub", "git"]
        return guesses.map(Paths.h).filter(Paths.isDirectory)
    }

    static func save(_ roots: [URL]) {
        UserDefaults.standard.set(roots.map(\.path), forKey: defaultsKey)
    }

    struct Found {
        let url: URL
        let rule: Rule
        let project: URL
    }

    static func scan(roots: [URL], progress: @escaping Progress) async -> [StorageGroup] {
        progress("Looking for build folders…")
        let found = await Task.detached(priority: .userInitiated) { () -> [Found] in
            var out: [Found] = []
            for root in roots { walk(root, depth: 0, into: &out) }
            return out
        }.value

        progress("Measuring \(found.count) build folders…")
        let sizes = await ScanKit.sizes(found.map(\.url))

        var byRule: [String: [StorageItem]] = [:]
        for f in found {
            let bytes = sizes[f.url.standardizedFileURL.path]?.bytes ?? 0
            guard bytes > 1_000_000 else { continue }
            let touched = lastActivity(in: f.project, skipping: f.url.lastPathComponent)
            let idle = touched.map { Fmt.days(since: $0) > 30 } ?? false
            byRule[f.rule.title, default: []].append(StorageItem(
                id: f.url.path, title: f.project.lastPathComponent,
                subtitle: Paths.tilde(f.url), url: f.url, bytes: bytes,
                safety: .safe, action: .remove([f.url]), icon: .file(f.project),
                date: touched, dateLabel: "Edited", staleDate: idle, recommended: idle))
        }

        var groups: [StorageGroup] = []
        for (title, items) in byRule {
            let rule = rules.first { $0.title == title }!
            groups.append(StorageGroup(
                id: "proj.\(rule.folder)", title: title, note: rule.note,
                symbol: "shippingbox", items: items.sorted(by: ScanKit.bySize)))
        }
        return groups.sorted { $0.total > $1.total }
    }

    private static func walk(_ dir: URL, depth: Int, into out: inout [Found]) {
        guard depth <= 7 else { return }
        let keys: [URLResourceKey] = [.isDirectoryKey, .isSymbolicLinkKey, .isPackageKey]
        let kids = Paths.children(dir, keys: keys)
        let names = Set(kids.map(\.lastPathComponent))

        for kid in kids {
            guard let v = try? kid.resourceValues(forKeys: Set(keys)),
                  v.isDirectory == true, v.isSymbolicLink != true else { continue }
            let name = kid.lastPathComponent

            if let candidates = rulesByFolder[name] {
                if let rule = candidates.first(where: { matches($0, kid, siblings: names) }) {
                    out.append(Found(url: kid, rule: rule, project: dir))
                    continue
                }
            }
            if skipNames.contains(name) || name.hasPrefix(".") || v.isPackage == true || name == "node_modules" { continue }
            walk(kid, depth: depth + 1, into: &out)
        }
    }

    private static func matches(_ rule: Rule, _ folder: URL, siblings: Set<String>) -> Bool {
        if !rule.markers.isEmpty, !rule.markers.contains(where: siblings.contains) { return false }
        if let inside = rule.inside, !Paths.exists(folder.appendingPathComponent(inside)) { return false }
        return true
    }

    /// Newest change among the project's own files, ignoring the build folder itself.
    private static func lastActivity(in project: URL, skipping: String) -> Date? {
        var dates: [Date] = []
        if let d = Paths.modified(project.appendingPathComponent(".git/index")) { dates.append(d) }
        for kid in Paths.children(project, keys: [.contentModificationDateKey]) where kid.lastPathComponent != skipping {
            if rulesByFolder[kid.lastPathComponent] != nil || kid.lastPathComponent == ".DS_Store" { continue }
            if let d = Paths.modified(kid) { dates.append(d) }
        }
        return dates.max()
    }
}
